// Builds the hosted copy of the hub and the Vercel deploy files. Run after editing hub.html:
//   node tools/build-hub.js
// 1. hub/index.html = hub.html plus the web app manifest link, with the home-screen icon served as a file.
// 2. tools/hub-deploy/build.sh pulls hub/ from GitHub at build time and checks every file's SHA1, so the
//    deployed site is byte-for-byte what is in git. Commit and push hub/ BEFORE deploying.
const fs = require('fs'); const path = require('path'); const crypto = require('crypto');
const root = path.join(__dirname, '..');
const BRANCH = 'claude/gifted-edison-7f7zwz';
const RAW = 'https://raw.githubusercontent.com/shanemichael631-code/READ-ME-/' + BRANCH + '/hub';

let html = fs.readFileSync(path.join(root, 'hub.html'), 'utf8');
const anchor = '<meta name="apple-mobile-web-app-title" content="Nova Hub">\n';
if (!html.includes(anchor)) throw new Error('hub.html changed: anchor line for the manifest link not found');
html = html.replace(anchor, anchor + '<link rel="manifest" href="/manifest.webmanifest">\n');
html = html.replace(/<link rel="apple-touch-icon" sizes="180x180" href="data:image\/png;base64,[^"]+">/, '<link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png">');
if (!html.includes('href="/apple-touch-icon.png"')) throw new Error('apple-touch-icon data URI not found in hub.html');
fs.mkdirSync(path.join(root, 'hub'), { recursive: true });
fs.writeFileSync(path.join(root, 'hub', 'index.html'), html);
console.log('wrote hub/index.html', html.length, 'bytes');

const files = ['index.html', 'manifest.webmanifest', 'apple-touch-icon.png', 'icon-192.png', 'icon-512.png', 'icon-192-maskable.png', 'icon-512-maskable.png'];
const sums = files.map((f) => crypto.createHash('sha1').update(fs.readFileSync(path.join(root, 'hub', f))).digest('hex') + '  ' + f);
const sh = [
  '#!/usr/bin/env bash',
  '# Nova Hub deploy (generated by tools/build-hub.js). Pulls hub/ from the public GitHub repo at build time',
  '# and verifies every file against the checksums below, so the site is byte-for-byte what is in git.',
  'set -euo pipefail',
  'BASE="' + RAW + '"',
  'mkdir -p public',
  'for f in ' + files.join(' ') + '; do',
  '  curl -fsSL "$BASE/$f?nocache=$(date +%s)" -o "public/$f"',
  'done',
  'cd public',
  "sha1sum -c <<'SUMS'",
  ...sums,
  'SUMS',
  'ls -la',
  '',
].join('\n');
fs.mkdirSync(path.join(root, 'tools', 'hub-deploy'), { recursive: true });
fs.writeFileSync(path.join(root, 'tools', 'hub-deploy', 'build.sh'), sh);
fs.writeFileSync(path.join(root, 'tools', 'hub-deploy', 'package.json'), '{"name":"nova-hub","private":true,"scripts":{"build":"bash build.sh"}}\n');
console.log('wrote tools/hub-deploy/build.sh and package.json');
